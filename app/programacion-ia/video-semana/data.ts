  resumen: string;
  bloques: BloqueGuion[]; // guion de la grabación (vacío si el guion es la página)
  puntos?: string[]; // «En este vídeo», cuando no hay guion publicado
  capitulos?: [string, string][]; // [«2:27», «Paso 1 · Activar GitHub Pages»]
